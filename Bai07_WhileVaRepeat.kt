fun main() {
    println("Đếm ngược bằng while:")
    var dem = 10
    while (dem >= 1) {
        println(dem)
        dem--
    }

    println("In 5 lần bằng repeat:")
    repeat(5) {
        println("Học Kotlin thật vui!")
    }

    // while dung khi lap theo dieu kien, repeat dung khi biet truoc so lan lap
}
